import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const site = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const root = path.resolve(site, '..');
const library = path.join(root, 'library');
const catalogPath = path.join(library, 'catalog.json');
const catalog = JSON.parse(fs.readFileSync(catalogPath, 'utf8'));
const checkOnly = process.argv.includes('--check');
const refreshHashes = process.argv.includes('--refresh-hashes');
const destination = path.join(site, 'src/content/docs/library');
const publicDestination = path.join(site, 'public/library');
const generatedNotice = 'Generated by site/scripts/sync-library.mjs. Edit library/; this entire directory is replaced on sync.\n';
const base = `/${(process.env.SITE_BASE || '').replace(/^\/+|\/+$/g, '')}`.replace(/^\/$/, '');
const publicPath = (value) => `${base}${value}`;
const sha256 = (bytes) => crypto.createHash('sha256').update(bytes).digest('hex');
const forbidden = /\/Users\/|\/Volumes\/|WhatsApp Chat|file:\/\//;
const fail = (message) => { throw new Error(`Library catalog: ${message}`); };
const statusLabels = {
  'revised-draft': 'Revised manuscript · draft',
  'companion-draft': 'Companion manuscript · unedited',
  illustration: 'Illustration · creator unverified',
};

if (checkOnly && refreshHashes) fail('--check is read-only; run --refresh-hashes separately after reviewing source changes');
if (catalog.schemaVersion !== 1 || !Array.isArray(catalog.documents)) fail('unsupported schema');
if (forbidden.test(JSON.stringify(catalog))) fail('private source location in public metadata');
const ids = new Set();
for (const document of catalog.documents) {
  if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(document.id) || ids.has(document.id)) fail('invalid or duplicate id');
  ids.add(document.id);
}

for (const document of catalog.documents) {
  if (!document.title || !document.summary || !document.authors?.length || !statusLabels[document.status]) fail(`incomplete metadata: ${document.id}`);
  if (document.reader !== `/library/${document.id}/`) fail(`unstable reader path: ${document.id}`);
  if (!document.rights?.note) fail(`missing work-specific rights statement: ${document.id}`);
  if (document.related.some((id) => !ids.has(id) || id === document.id)) fail(`invalid relationship: ${document.id}`);
  if (document.files.filter((file) => file.format === 'markdown').length !== 1) fail(`one reader required: ${document.id}`);
  const formats = new Set();
  const readerText = fs.readFileSync(path.join(root, document.files.find((file) => file.format === 'markdown').source), 'utf8');
  for (const file of document.files) {
    if (formats.has(file.format)) fail(`duplicate file format: ${document.id}`);
    formats.add(file.format);
    const source = path.resolve(root, file.source);
    if (!source.startsWith(`${library}${path.sep}`) || !fs.realpathSync(source).startsWith(`${library}${path.sep}`)) fail(`file outside library: ${document.id}`);
    if (file.path !== `/library/files/${document.id}/${path.basename(source)}`) fail(`invalid download path: ${document.id}`);
    const bytes = fs.readFileSync(source);
    if (refreshHashes) {
      file.sha256 = sha256(bytes);
      file.bytes = bytes.length;
    }
    if (sha256(bytes) !== file.sha256 || bytes.length !== file.bytes) fail(`content changed; review and refresh hashes: ${file.source}`);
    if (['tex', 'markdown'].includes(file.format) && forbidden.test(bytes.toString('utf8'))) fail(`private source location: ${document.id}`);
    if (file.format === 'pdf' && bytes.subarray(0, 5).toString() !== '%PDF-') fail(`invalid PDF signature: ${document.id}`);
    if (file.format === 'tex') {
      const text = bytes.toString('utf8');
      const references = [...text.matchAll(/\\bibitem\{([^}]+)\}/g)];
      const readerReferences = [...readerText.matchAll(/^### Reference (\d+)$/gm)];
      if (references.length !== readerReferences.length) fail(`bibliography entries omitted: ${document.id}`);
      const citations = [...text.matchAll(/\\cite\{([^}]+)\}/g)].reduce((count, match) => count + match[1].split(',').length, 0);
      if (citations !== [...readerText.matchAll(/\]\(#reference-\d+\)/g)].length) fail(`citation links omitted: ${document.id}`);
      if (text.includes('\\begin{abstract}') && !/^## Abstract$/m.test(readerText)) fail(`abstract omitted: ${document.id}`);
    }
    if (file.format === 'markdown') {
      const body = bytes.toString('utf8');
      if (/class="tabularx"|data-reference-type=|\$`/.test(body)) fail(`unconverted reader construct: ${document.id}`);
      const targets = new Set([...body.matchAll(/^### Reference (\d+)$/gm)].map((match) => match[1]));
      for (const match of body.matchAll(/\]\(#reference-(\d+)\)/g)) {
        if (!targets.has(match[1])) fail(`unresolved citation: ${document.id}`);
      }
    }
  }
}
// These exact directories are exclusively generated. Validate both before any
// mutation; never follow a symlink when replacing generated output.
for (const directory of [destination, publicDestination]) {
  let current = site;
  for (const segment of path.relative(site, directory).split(path.sep)) {
    current = path.join(current, segment);
    let stat;
    try {
      stat = fs.lstatSync(current);
    } catch (error) {
      if (error.code === 'ENOENT') break;
      throw error;
    }
    if (stat.isSymbolicLink() || !stat.isDirectory()) {
      fail(`generated output must use directories, not files or symlinks: ${path.relative(site, current)}`);
    }
  }
}
if (refreshHashes) fs.writeFileSync(catalogPath, JSON.stringify(catalog, null, 2) + '\n');

if (!checkOnly) {
  // Catalog removal must also remove stale public pages and downloadable files.
  // All source/hash/relationship checks above finish before deleting any output.
  for (const directory of [destination, publicDestination]) {
    fs.rmSync(directory, { recursive: true, force: true });
    fs.mkdirSync(directory, { recursive: true });
    fs.writeFileSync(path.join(directory, '.generated'), generatedNotice);
  }
  for (const document of catalog.documents) {
    const markdown = document.files.find((file) => file.format === 'markdown');
    let body = fs.readFileSync(path.join(root, markdown.source), 'utf8');
    body = body.replace(/\]\(\/library\//g, `](${publicPath('/library/')}`);
    const downloads = document.files.map((file) => {
      const labels = { pdf: 'PDF', tex: 'LaTeX source', markdown: 'Reader Markdown', jpg: 'Original image' };
      return `[${labels[file.format] || file.format}](${publicPath(file.path)})`;
    }).join(' · ');
    const related = document.related.map((id) => {
      const other = catalog.documents.find((entry) => entry.id === id);
      return `- [${other.title}](${publicPath(other.reader)})`;
    }).join('\n');
    const edition = [
      `**${document.authors.join(', ')}** · ${document.date} · ${statusLabels[document.status]}`,
      `*${document.subtitle}*`,
      downloads,
      `<details>\n<summary>Edition, evidence, and attribution</summary>\n\n${document.provenance.sourceDescription}\n\n${document.evidenceNote}\n\n${document.rights.note}\n\nFile integrity is recorded in the [document catalog](${publicPath('/library/catalog.json')}).\n\n</details>`,
    ].join('\n\n');
    const frontmatter = `---\ntitle: ${JSON.stringify(document.title)}\ndescription: ${JSON.stringify(document.summary)}\n---\n\n`;
    fs.writeFileSync(path.join(destination, `${document.id}.md`), `${frontmatter}<!-- ${generatedNotice.trim()} -->\n\n${edition}\n\n${body}\n## Related reading\n\n${related}\n`);
    for (const file of document.files) {
      const output = path.join(site, 'public', file.path);
      fs.mkdirSync(path.dirname(output), { recursive: true });
      fs.copyFileSync(path.join(root, file.source), output);
    }
  }
  fs.mkdirSync(path.join(site, 'public/library'), { recursive: true });
  fs.writeFileSync(path.join(site, 'public/library/catalog.json'), JSON.stringify(catalog, null, 2) + '\n');
}

console.log(`${checkOnly ? 'Validated' : 'Synced'} ${catalog.documents.length} curated readers and ${catalog.documents.reduce((count, document) => count + document.files.length, 0)} source/reader downloads.`);
